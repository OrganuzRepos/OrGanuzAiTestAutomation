#!/usr/bin/env node
/**
 * One source of truth for "how many tests are there".
 *
 * The count lived in prose in four files and drifted in three of them: CLAUDE.md
 * said 196/69, Readme.md said 191/64, docs/test-plans/README.md said 187/60. Only
 * one was right, and nothing told a reader which. A number in a document that
 * nobody verifies is worse than no number, because it still gets quoted.
 *
 * So the number stops being written by hand. This script asks Playwright what it
 * discovers and rewrites a delimited block in each document:
 *
 *     <!-- test-counts:start -->
 *     ...generated table...
 *     <!-- test-counts:end -->
 *
 * Nothing outside the markers is touched, so the prose around them stays owned by
 * whoever wrote it.
 *
 *   node scripts/sync-test-counts.mjs           rewrite the blocks
 *   node scripts/sync-test-counts.mjs --check   fail if any block is stale (CI)
 *
 * `--check` is the half that matters: it turns "someone forgot to update the docs"
 * from a thing a reader discovers into a thing the pipeline says out loud.
 *
 * Only projects Playwright actually discovers are listed. Disabled projects
 * (`chromium`, `product-setup`, `product-authenticated` — commented out in
 * playwright.config.ts) contribute nothing to `--list` and so appear nowhere here;
 * their counts stay prose, because a number nothing can verify should at least not
 * pretend otherwise.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- test-counts:start -->';
const END = '<!-- test-counts:end -->';

/** Files carrying the generated block. Add one here and it is kept in sync too. */
const TARGETS = ['CLAUDE.md', 'Readme.md', 'docs/test-plans/README.md'];

/** Ask Playwright what it discovers. This is the only place a count comes from. */
function discover() {
  const raw = execFileSync(
    'npx',
    ['playwright', 'test', '--list', '--reporter=json'],
    { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] },
  );
  const counts = new Map();
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      for (const test of spec.tests ?? []) {
        const project = test.projectName || '(no project)';
        counts.set(project, (counts.get(project) ?? 0) + 1);
      }
    }
    for (const child of suite.suites ?? []) walk(child);
  };
  for (const suite of JSON.parse(raw).suites ?? []) walk(suite);
  if (counts.size === 0) {
    throw new Error('Playwright discovered no tests — refusing to write a zero into the docs');
  }
  return [...counts.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function render(counts) {
  const total = counts.reduce((sum, [, n]) => sum + n, 0);
  const rows = counts.map(([project, n]) => `| \`${project}\` | ${n} |`).join('\n');
  return [
    START,
    '',
    '<!-- Generated by scripts/sync-test-counts.mjs — do not edit by hand.',
    '     Run `npm run docs:counts` after adding or removing a test. -->',
    '',
    '| Project | Discovered tests |',
    '|---|---:|',
    rows,
    `| **Total** | **${total}** |`,
    '',
    'Counts come from `npx playwright test --list`. Projects commented out in',
    '`playwright.config.ts` discover nothing and are absent from this table.',
    '',
    END,
  ].join('\n');
}

const counts = discover();
const block = render(counts);
const check = process.argv.includes('--check');
const stale = [];
const missing = [];

for (const relative of TARGETS) {
  const file = path.join(ROOT, relative);
  const text = readFileSync(file, 'utf8');
  const from = text.indexOf(START);
  const to = text.indexOf(END);

  if (from === -1 || to === -1) {
    missing.push(relative);
    continue;
  }
  const current = text.slice(from, to + END.length);
  if (current === block) continue;

  if (check) {
    stale.push(relative);
  } else {
    writeFileSync(file, text.slice(0, from) + block + text.slice(to + END.length));
    console.log(`updated  ${relative}`);
  }
}

if (missing.length) {
  console.error(
    `\nNo ${START} … ${END} block in:\n` +
      missing.map((f) => `  ${f}`).join('\n') +
      '\nAdd the markers where the counts belong, then re-run.',
  );
  process.exit(1);
}

if (check && stale.length) {
  console.error(
    '\nTest counts in these documents are out of date:\n' +
      stale.map((f) => `  ${f}`).join('\n') +
      '\n\nRun `npm run docs:counts` and commit the result.\n' +
      '\nWhat Playwright currently discovers:\n' +
      counts.map(([p, n]) => `  ${p.padEnd(16)} ${n}`).join('\n') +
      `\n  ${'TOTAL'.padEnd(16)} ${counts.reduce((s, [, n]) => s + n, 0)}\n`,
  );
  process.exit(1);
}

console.log(
  check
    ? 'Test counts are in sync.'
    : `Done — ${counts.reduce((s, [, n]) => s + n, 0)} tests across ${counts.length} projects.`,
);
